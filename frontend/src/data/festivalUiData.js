export function formatTime(value) {
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return `${value || ""}`.slice(11, 16) || "--:--";
  return `${String(date.getHours()).padStart(2, "0")}:${String(date.getMinutes()).padStart(2, "0")}`;
}
